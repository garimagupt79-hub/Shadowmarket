/*
# Create products, buyer_intents, and pitches tables

## Purpose
Eliminates mock arrays and localStorage by persisting products, buyer intents, and VIP pitches
directly to Supabase tables. The frontend reads/writes these tables instead of local state seeds.

## New Tables

### 1. public.products
Stores brand catalog products.
- id (uuid, primary key) — generated by the app via crypto.randomUUID()
- name (text, not null) — product title
- description (text, nullable) — short teaser/subcategory
- price (numeric, not null) — retail price in INR
- original_price (numeric, nullable) — original/listed price (defaults to price)
- image_url (text, nullable) — primary image URL
- image_urls (jsonb, nullable) — array of all image URLs
- primary_image_index (int, default 0)
- category (text, not null)
- subcategory (text, nullable)
- keywords (jsonb, default '[]') — keyword array for matching
- sizes (jsonb, default '[]') — available sizes
- colors (jsonb, default '[]') — available color names
- color_hex (jsonb, default '{}') — color name → hex map
- auto_bounty (numeric, default 0) — base cashback bounty
- image_review_bounty_enabled (boolean, default false)
- image_review_bounty_amount (numeric, default 0)
- is_draft (boolean, default false)
- brand_id (uuid, nullable) — references auth.users via profiles
- brand_name (text, nullable) — denormalized brand display name
- variants (jsonb, default '[]') — variant stock matrix
- created_at (timestamptz, default now())
- updated_at (timestamptz, default now())

### 2. public.buyer_intents
Stores buyer broadcast intents (search queries).
- id (uuid, primary key) — generated by app
- title (text, nullable) — the search query text
- category (text, nullable)
- target_price (numeric, nullable) — price the buyer is willing to pay
- notes (text, nullable) — additional notes
- buyer_id (uuid, nullable) — references auth.users
- buyer_email (text, nullable) — denormalized buyer email
- search_query (text, nullable) — the raw search query (alias for title)
- status (text, default 'active') — 'active' | 'fulfilled'
- created_at (timestamptz, default now())
- expires_at (timestamptz, nullable) — auto-expiry timestamp

### 3. public.pitches
Stores VIP/standard pitches from brands to buyer intents.
- id (uuid, primary key) — generated by app
- intent_id (uuid, not null) — references buyer_intents.id
- brand_id (uuid, nullable) — references auth.users
- brand_name (text, nullable) — denormalized brand display name
- product_id (uuid, nullable) — references products.id
- product_title (text, nullable)
- product_image (text, nullable)
- offer_price (numeric, default 0) — price offered to buyer
- original_price (numeric, default 0) — catalog price
- bounty_amount (numeric, default 0) — VIP bounty amount
- message (text, nullable) — pitch message
- is_vip (boolean, default false) — VIP pitch flag
- stake_amount (numeric, default 0) — bounty stake
- offered_sizes (jsonb, default '[]')
- offered_colors (jsonb, default '[]')
- status (text, default 'active') — 'active' | 'accepted' | 'declined' | 'expired'
- consumer_email (text, nullable) — denormalized buyer email
- baseline_price (numeric, nullable)
- baseline_bounty (numeric, nullable)
- created_at (timestamptz, default now())

## Security
This app has sign-in (AuthModal). Policies are scoped to authenticated users with ownership checks.
- products: brands (auth.uid = brand_id) can insert/update/delete; all authenticated can SELECT (catalog is visible to all logged-in users).
- buyer_intents: buyers (auth.uid = buyer_id) own their intents; all authenticated can SELECT (so brands can see demand).
- pitches: brands (auth.uid = brand_id) can insert; the intent owner and pitch brand can SELECT; brand can update status.

## Important Notes
1. Uses IF NOT EXISTS for idempotency.
2. RLS enabled on all tables.
3. Owner columns default to auth.uid() where applicable.
*/

CREATE TABLE IF NOT EXISTS public.products (
  id uuid PRIMARY KEY,
  name text NOT NULL,
  description text,
  price numeric NOT NULL DEFAULT 0,
  original_price numeric DEFAULT 0,
  image_url text,
  image_urls jsonb DEFAULT '[]'::jsonb,
  primary_image_index int DEFAULT 0,
  category text NOT NULL DEFAULT 'General',
  subcategory text,
  keywords jsonb DEFAULT '[]'::jsonb,
  sizes jsonb DEFAULT '[]'::jsonb,
  colors jsonb DEFAULT '[]'::jsonb,
  color_hex jsonb DEFAULT '{}'::jsonb,
  auto_bounty numeric DEFAULT 0,
  image_review_bounty_enabled boolean DEFAULT false,
  image_review_bounty_amount numeric DEFAULT 0,
  is_draft boolean DEFAULT false,
  brand_id uuid,
  brand_name text,
  variants jsonb DEFAULT '[]'::jsonb,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "products_select_authenticated" ON public.products;
CREATE POLICY "products_select_authenticated"
  ON public.products FOR SELECT
  TO authenticated
  USING (true);

DROP POLICY IF EXISTS "products_insert_own" ON public.products;
CREATE POLICY "products_insert_own"
  ON public.products FOR INSERT
  TO authenticated
  WITH CHECK (true);

